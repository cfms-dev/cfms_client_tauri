import { colorPalettes, DEFAULT_PALETTE_ID, type ColorPalette } from './palettes.ts';
import { createPaletteTheme, SERIF_FONT } from './theme.ts';

/** Shared renderer so CSS generation can be checked against the runtime factory. */
export function generateThemeCss(palettes: readonly ColorPalette[] = Object.values(colorPalettes)): string {
  const blocks = palettes.flatMap(palette => (['light', 'dark'] as const).map(mode => {
    // Keep specificity below accessibility overrides. Missing data-palette uses
    // the default before the appearance store initializes.
    const match = palette.id === DEFAULT_PALETTE_ID
      ? `:not([data-palette]), [data-palette="${palette.id}"]`
      : `[data-palette="${palette.id}"]`;
    return `html[data-theme="${mode}"]:where(${match}) {\n`
      + Object.entries(createPaletteTheme(palette, mode)).map(([key, value]) => `  --${key}: ${value};`).join('\n')
      + '\n}\n';
  }));
  const durations = Object.keys(createPaletteTheme(palettes[0], 'light')).filter(key => key.startsWith('duration'));
  return '/* Generated by pnpm assets:fluent. Edit palette definitions or theme.ts, not this file. */\n'
    + blocks.join('\n')
    + `\n:root { --font-cfms-serif: ${SERIF_FONT}; }\n`
    + '\n/* CSS inheritance reaches Fluent shadow roots; document-wide * does not. */\n'
    + 'html[data-theme][data-reduce-motion="true"] {\n'
    + durations.map(key => `  --${key}: 0.01ms;`).join('\n')
    + '\n}\n';
}
