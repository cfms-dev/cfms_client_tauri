import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ICON_MAP } from '../src/lib/shared/fluent/icon-map.ts';

const packageRoot = new URL('../node_modules/@fluentui/svg-icons/icons/', import.meta.url);
const imports = new Map();
const duotoneSlugs = new Set([
  'folder_add', 'folder_arrow_up', 'folder_arrow_right',
  'copy', 'shield_settings', 'password_reset', 'person_circle',
]);
// Primary means the main subject, independently of which part carries brand color.
const brandPrimarySlugs = new Set(['copy', 'person_circle']);
const duotoneImports = new Map();
function duotoneAsset(slug, size) {
  const file = `${slug}_${size}.svg`;
  if (!existsSync(new URL('../src/lib/shared/fluent/assets/duotone/' + file, import.meta.url))) {
    throw new Error('Missing duotone icon: ' + file);
  }
  if (!duotoneImports.has(file)) duotoneImports.set(file, 'duotone' + duotoneImports.size);
  return duotoneImports.get(file);
}
function asset(slug, size, style) {
  const sizes = [...new Set([size, 24, 20, 48])];
  const styles = [...new Set([style, 'regular'])];
  const file = styles.flatMap((variant) => sizes.map((dimension) => `${slug}_${dimension}_${variant}.svg`))
    .find((candidate) => existsSync(new URL(candidate, packageRoot)));
  if (!file) throw new Error('Missing Fluent icon: ' + slug);
  if (!imports.has(file)) imports.set(file, 'svg' + imports.size);
  return imports.get(file);
}
const entries = Object.entries(ICON_MAP).map(([key, slug]) =>
  '  ' + key + ': { regular: ' + asset(slug, 24, 'regular') + ', filled: ' + asset(slug, 24, 'filled')
  + ', small: ' + asset(slug, 20, 'regular') + ', smallFilled: ' + asset(slug, 20, 'filled')
  + (duotoneSlugs.has(slug) ? ', duotone: ' + duotoneAsset(slug, 24) + ', smallDuotone: ' + duotoneAsset(slug, 20)
    + ", primaryTone: '" + (brandPrimarySlugs.has(slug) ? 'brand' : 'neutral') + "'" : '') + ' },',
);
const output = '// Generated by pnpm assets:fluent. Edit fluent/icon-map.ts.\n'
  + [...imports].map(([file, name]) => "import " + name + " from '@fluentui/svg-icons/icons/" + file + "?raw';").join('\n')
  + '\n' + [...duotoneImports].map(([file, name]) => "import " + name + " from './assets/duotone/" + file + "?raw';").join('\n')
  + '\n\nexport const ICON_VARIANTS = {\n' + entries.join('\n') + '\n} as const;\n';
const target = fileURLToPath(new URL('../src/lib/shared/fluent/icons.generated.ts', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Fluent icons are stale. Run pnpm assets:fluent.');
} else {
  writeFileSync(target, output);
}
